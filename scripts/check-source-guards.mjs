#!/usr/bin/env node
/**
 * OCSO source guards (T1.1.2). Run as the root `pnpm lint`.
 *
 * Enforces the mechanical parts of the build rules (docs/99-BUILD-RULES.md §2)
 * and the workspace boundaries from ADR-001, over apps/*, packages/* and
 * examples/* (their src/ trees; a package without src/ is scanned from its root):
 *   1. File size: hand-written source files over 300 lines warn, over 500 fail.
 *   2. Import boundaries:
 *        - packages/* and examples/* never import an app (apps/*),
 *        - an app never imports another app,
 *        - @ocso/domain imports (and depends on) no other @ocso package,
 *        - relative imports never escape into another workspace package
 *          (use the package name so the dependency is declared and built).
 *   3. No dependency cycles between workspace packages (package.json deps,
 *      devDependencies and peerDependencies).
 *
 * Usage: node scripts/check-source-guards.mjs [--json] [--root <dir>]
 * Exit code: 0 when there are no failures (warnings allowed), 1 otherwise, 2 on bad usage.
 * Plain Node, no dependencies: it must run before `pnpm install` finishes being trusted.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const WARN_LINES = 300;
const FAIL_LINES = 500;
const WORKSPACE_GROUPS = ['apps', 'packages', 'examples'];
const SOURCE_EXT = /\.(?:ts|tsx|mts|cts)$/;
const SKIP_DIRS = new Set(['node_modules', 'dist', '.next', '.turbo', 'coverage', 'migrations', 'generated', '__generated__']);
const TEST_FILE = /\.(?:test|spec)\.(?:ts|tsx|mts|cts)$/;
/** Extra directories skipped when a workspace has no src/ (e.g. Next.js apps keep app/, lib/, components/ at the root). */
const ROOT_SKIP_DIRS = new Set(['test', 'tests', '__tests__', 'e2e', 'test-results', 'playwright-report', 'public']);
const ROOT_CONFIG_FILE = /^[\w.-]+\.config\.(?:ts|mts|cts)$/;
const GENERATED_MARKER = /@generated\b|\bauto-generated\b|\bcode generated by\b|\bdo not edit\b/i;
const DOMAIN = '@ocso/domain';

// ───────────────────────────── CLI ─────────────────────────────

function parseArgs(argv) {
  const args = { json: false, root: resolve(dirname(fileURLToPath(import.meta.url)), '..') };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--json') args.json = true;
    else if (a === '--root') {
      const value = argv[++i];
      if (!value) usage('--root needs a directory');
      args.root = resolve(value);
    } else if (a === '--help' || a === '-h') usage(null, 0);
    else usage(`unknown argument ${a}`);
  }
  return args;
}

function usage(problem, code = 2) {
  if (problem) console.error(`check-source-guards: ${problem}`);
  console.error('usage: node scripts/check-source-guards.mjs [--json] [--root <dir>]');
  process.exit(code);
}

// ─────────────────────────── Workspace ──────────────────────────

const toPosix = (p) => p.split(sep).join('/');

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

/** Workspace members under apps/*, packages/*, examples/* that have a package.json. */
function discoverWorkspaces(root) {
  const workspaces = [];
  for (const group of WORKSPACE_GROUPS) {
    const groupDir = join(root, group);
    if (!existsSync(groupDir)) continue;
    for (const entry of readdirSync(groupDir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const dir = join(groupDir, entry.name);
      const manifestPath = join(dir, 'package.json');
      if (!existsSync(manifestPath)) continue;
      const manifest = readJson(manifestPath);
      workspaces.push({
        name: manifest.name ?? `${group}/${entry.name}`,
        group,
        dir,
        relDir: toPosix(relative(root, dir)),
        manifest,
      });
    }
  }
  const names = new Set(workspaces.map((w) => w.name));
  for (const ws of workspaces) {
    const declared = { ...ws.manifest.dependencies, ...ws.manifest.devDependencies, ...ws.manifest.peerDependencies };
    ws.deps = Object.entries(declared)
      .filter(([dep, range]) => dep !== ws.name && (names.has(dep) || String(range).startsWith('workspace:')))
      .map(([dep]) => dep)
      .sort();
    ws.allDeclared = Object.keys(declared);
  }
  return workspaces;
}

/** The workspace containing an absolute path (longest directory prefix), or null. */
function workspaceOf(workspaces, absPath) {
  let best = null;
  for (const ws of workspaces) {
    if ((absPath === ws.dir || absPath.startsWith(ws.dir + sep)) && (!best || ws.dir.length > best.dir.length)) best = ws;
  }
  return best;
}

/**
 * Hand-written source of a workspace: its src/ tree, or — for packages without
 * src/ such as the Next.js app — the package root minus tests and tool configs.
 */
function listSourceFiles(wsDir) {
  const srcDir = join(wsDir, 'src');
  const rootMode = !existsSync(srcDir);
  const files = [];
  const walk = (d, atRoot) => {
    for (const entry of readdirSync(d, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        const skip = SKIP_DIRS.has(entry.name) || entry.name.startsWith('.') || (rootMode && ROOT_SKIP_DIRS.has(entry.name));
        if (!skip) walk(join(d, entry.name), false);
      } else if (entry.isFile() && SOURCE_EXT.test(entry.name) && !/\.d\.(?:ts|mts|cts)$/.test(entry.name)) {
        if (rootMode && atRoot && ROOT_CONFIG_FILE.test(entry.name)) continue;
        files.push(join(d, entry.name));
      }
    }
  };
  walk(rootMode ? wsDir : srcDir, true);
  return files.sort();
}

// ─────────────────────────── Parsing ────────────────────────────

export function countLines(text) {
  if (text.length === 0) return 0;
  const lines = text.split('\n').length;
  return text.endsWith('\n') ? lines - 1 : lines;
}

function isGenerated(text) {
  return GENERATED_MARKER.test(text.split('\n', 10).join('\n'));
}

const REGEX_PRECEDERS = new Set(['(', ',', '=', ':', '[', '!', '&', '|', '?', '{', '}', ';', '+', '-', '*', '%', '<', '>', '~', '^']);
const REGEX_KEYWORDS = new Set(['return', 'typeof', 'case', 'do', 'else', 'in', 'of', 'void', 'yield', 'await', 'delete', 'instanceof', 'new', 'throw']);

/** Can a `/` at this point start a regex literal (vs. a division)? Looks back at emitted code. */
function slashStartsRegex(out) {
  let j = out.length - 1;
  while (j >= 0 && /\s/.test(out[j])) j--;
  if (j < 0) return true;
  const ch = out[j];
  if (/[\w$]/.test(ch)) {
    let k = j;
    while (k >= 0 && /[\w$]/.test(out[k])) k--;
    return REGEX_KEYWORDS.has(out.slice(k + 1, j + 1));
  }
  // `)` and `]` end expressions, so a following `/` is a division.
  return REGEX_PRECEDERS.has(ch);
}

const blank = (s) => s.replace(/[^\n]/g, ' ');

/**
 * Blank out comments, template literals and regex literals while keeping
 * ordinary string literals (import specifiers live in those). Good enough for
 * import extraction; not a full TypeScript lexer.
 */
export function stripNonCode(src) {
  let out = '';
  let i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i];
    const d = src[i + 1];
    if (c === '/' && d === '/') {
      const end = src.indexOf('\n', i);
      i = end === -1 ? n : end;
      continue;
    }
    if (c === '/' && d === '*') {
      const close = src.indexOf('*/', i + 2);
      const end = close === -1 ? n : close + 2;
      out += blank(src.slice(i, end));
      i = end;
      continue;
    }
    if (c === '"' || c === "'") {
      let j = i + 1;
      while (j < n && src[j] !== c && src[j] !== '\n') j += src[j] === '\\' ? 2 : 1;
      out += src.slice(i, j + 1);
      i = j + 1;
      continue;
    }
    if (c === '`') {
      let j = i + 1;
      let depth = 0;
      while (j < n) {
        const t = src[j];
        if (t === '\\') {
          j += 2;
          continue;
        }
        if (depth === 0 && t === '`') break;
        if (t === '$' && src[j + 1] === '{') {
          depth++;
          j += 2;
          continue;
        }
        if (depth > 0 && t === '{') depth++;
        else if (depth > 0 && t === '}') depth--;
        j++;
      }
      out += blank(src.slice(i, j + 1));
      i = j + 1;
      continue;
    }
    if (c === '/' && slashStartsRegex(out)) {
      let j = i + 1;
      let inClass = false;
      while (j < n && src[j] !== '\n') {
        const t = src[j];
        if (t === '\\') {
          j += 2;
          continue;
        }
        if (t === '[') inClass = true;
        else if (t === ']') inClass = false;
        else if (t === '/' && !inClass) break;
        j++;
      }
      j++;
      while (j < n && /[a-z]/i.test(src[j])) j++;
      out += blank(src.slice(i, j));
      i = j;
      continue;
    }
    out += c;
    i++;
  }
  return out;
}

const IMPORT_PATTERNS = [
  // import x from 'y'; import type { A } from "y"; import 'y'; export * from 'y'; export { a } from 'y' (multi-line ok)
  /(?:^|[^\w$.])(?:import|export)\s+(?:type\s+)?(?:[^'";]*?\sfrom\s*)?['"]([^'"\n]+)['"]/g,
  // dynamic import('y') and import-equals / CommonJS require('y')
  /(?:^|[^\w$.])import\s*\(\s*['"]([^'"\n]+)['"]\s*[,)]/g,
  /(?:^|[^\w$.])require\s*\(\s*['"]([^'"\n]+)['"]\s*\)/g,
];

/** Import specifiers with their 1-based line numbers. */
export function extractImports(src) {
  const code = stripNonCode(src);
  const found = new Map();
  for (const pattern of IMPORT_PATTERNS) {
    pattern.lastIndex = 0;
    let m;
    while ((m = pattern.exec(code))) {
      const specifierIndex = m.index + m[0].lastIndexOf(m[1]);
      const line = countLines(code.slice(0, specifierIndex + 1));
      found.set(`${line}:${m[1]}`, { specifier: m[1], line });
    }
  }
  return [...found.values()].sort((a, b) => a.line - b.line);
}

const packageNameOf = (specifier) => {
  const parts = specifier.split('/');
  return specifier.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
};

// ─────────────────────────── Checks ─────────────────────────────

function classifyEdge(from, to) {
  if (to.group === 'apps' && from.group !== 'apps') return { rule: 'package-imports-app', why: `${from.group}/* must not depend on apps (${to.name})` };
  if (to.group === 'apps' && from.group === 'apps') return { rule: 'app-imports-app', why: `apps must not depend on other apps (${to.name})` };
  if (from.name === DOMAIN) return { rule: 'domain-imports-workspace', why: `${DOMAIN} must not depend on other workspace packages (${to.name})` };
  return null;
}

function checkFileImports(ctx, ws, file, text) {
  const violations = [];
  const relFile = toPosix(relative(ctx.root, file));
  for (const { specifier, line } of extractImports(text)) {
    const at = `${relFile}:${line}`;
    if (specifier.startsWith('.')) {
      const target = resolve(dirname(file), specifier);
      if (target === ws.dir || target.startsWith(ws.dir + sep)) continue;
      const other = workspaceOf(ctx.workspaces, target);
      if (!other) {
        violations.push({ rule: 'relative-escapes-workspace', at, specifier, message: 'relative import leaves the workspace package; import through a package name' });
        continue;
      }
      const edge = classifyEdge(ws, other);
      violations.push({
        rule: edge?.rule ?? 'relative-cross-workspace',
        at,
        specifier,
        message: edge ? `${edge.why}; also: use the package name, not a relative path` : `relative import into ${other.name}; use the package name "${other.name}"`,
      });
      continue;
    }
    const name = packageNameOf(specifier);
    if (name === ws.name) continue;
    const target = ctx.byName.get(name);
    if (target) {
      const edge = classifyEdge(ws, target);
      if (edge) violations.push({ rule: edge.rule, at, specifier, message: edge.why });
    } else if (ws.name === DOMAIN && name.startsWith('@ocso/')) {
      violations.push({ rule: 'domain-imports-workspace', at, specifier, message: `${DOMAIN} must not import other @ocso packages (${name})` });
    }
  }
  return violations;
}

function checkManifestBoundaries(ctx) {
  const violations = [];
  for (const ws of ctx.workspaces) {
    const at = `${ws.relDir}/package.json`;
    for (const dep of ws.deps) {
      const target = ctx.byName.get(dep);
      const edge = target ? classifyEdge(ws, target) : null;
      if (edge) violations.push({ rule: edge.rule, at, specifier: dep, message: `declared dependency: ${edge.why}` });
    }
    if (ws.name === DOMAIN) {
      for (const dep of ws.allDeclared.filter((d) => d.startsWith('@ocso/') && !ws.deps.includes(d))) {
        violations.push({ rule: 'domain-imports-workspace', at, specifier: dep, message: `declared dependency: ${DOMAIN} must not depend on ${dep}` });
      }
    }
  }
  return violations;
}

/** Tarjan SCCs over workspace deps; one representative cycle path per cyclic component. */
export function findCycles(graph) {
  let index = 0;
  const idx = new Map();
  const low = new Map();
  const stack = [];
  const onStack = new Set();
  const components = [];
  const strongConnect = (v) => {
    idx.set(v, index);
    low.set(v, index);
    index++;
    stack.push(v);
    onStack.add(v);
    for (const w of graph.get(v) ?? []) {
      if (!graph.has(w)) continue;
      if (!idx.has(w)) {
        strongConnect(w);
        low.set(v, Math.min(low.get(v), low.get(w)));
      } else if (onStack.has(w)) low.set(v, Math.min(low.get(v), idx.get(w)));
    }
    if (low.get(v) === idx.get(v)) {
      const component = [];
      let w;
      do {
        w = stack.pop();
        onStack.delete(w);
        component.push(w);
      } while (w !== v);
      components.push(component);
    }
  };
  for (const v of [...graph.keys()].sort()) if (!idx.has(v)) strongConnect(v);

  const cycles = [];
  for (const component of components) {
    const members = new Set(component);
    const start = [...component].sort()[0];
    const selfLoop = (graph.get(start) ?? []).includes(start);
    if (component.length === 1 && !selfLoop) continue;
    // Shortest path start → … → start inside the component (BFS).
    const prev = new Map();
    const queue = [start];
    const seen = new Set([start]);
    let closing = null;
    while (queue.length && !closing) {
      const v = queue.shift();
      for (const w of [...(graph.get(v) ?? [])].sort()) {
        if (!members.has(w)) continue;
        if (w === start) {
          closing = v;
          break;
        }
        if (!seen.has(w)) {
          seen.add(w);
          prev.set(w, v);
          queue.push(w);
        }
      }
    }
    const path = [start];
    for (let v = closing; v && v !== start; v = prev.get(v)) path.splice(1, 0, v);
    cycles.push({ members: [...component].sort(), path: [...path, start] });
  }
  return cycles;
}

export function runGuards(root) {
  const workspaces = discoverWorkspaces(root);
  const ctx = { root, workspaces, byName: new Map(workspaces.map((w) => [w.name, w])) };
  const files = [];
  const violations = [];
  let scanned = 0;
  for (const ws of workspaces) {
    for (const file of listSourceFiles(ws.dir)) {
      const text = readFileSync(file, 'utf8');
      if (isGenerated(text)) continue;
      scanned++;
      violations.push(...checkFileImports(ctx, ws, file, text));
      if (TEST_FILE.test(file)) continue; // tests may reasonably differ (build rule §2)
      const lines = countLines(text);
      if (lines > WARN_LINES) files.push({ path: toPosix(relative(root, file)), lines, status: lines > FAIL_LINES ? 'FAIL' : 'WARN' });
    }
  }
  violations.push(...checkManifestBoundaries(ctx));
  files.sort((a, b) => b.lines - a.lines || a.path.localeCompare(b.path));
  const cycles = findCycles(new Map(workspaces.map((w) => [w.name, w.deps])));
  const failures = files.filter((f) => f.status === 'FAIL').length + violations.length + cycles.length;
  return {
    root,
    thresholds: { warnLines: WARN_LINES, failLines: FAIL_LINES },
    workspaces: workspaces.length,
    scanned,
    files,
    violations,
    cycles,
    warnings: files.filter((f) => f.status === 'WARN').length,
    failures,
    ok: failures === 0,
  };
}

// ─────────────────────────── Report ─────────────────────────────

function printReport(r) {
  const out = [];
  out.push(`OCSO source guards: ${r.scanned} hand-written source files in ${r.workspaces} workspace packages`);
  out.push('');
  if (r.files.length) {
    out.push(`File size (warn > ${r.thresholds.warnLines} lines, fail > ${r.thresholds.failLines}):`);
    const width = Math.max(4, ...r.files.map((f) => f.path.length));
    out.push(`  ${'STATUS'.padEnd(6)}  ${'LINES'.padStart(5)}  ${'PATH'.padEnd(width)}`);
    out.push(`  ${'-'.repeat(6)}  ${'-'.repeat(5)}  ${'-'.repeat(width)}`);
    for (const f of r.files) out.push(`  ${f.status.padEnd(6)}  ${String(f.lines).padStart(5)}  ${f.path}`);
  } else out.push(`File size: every file is at or under ${r.thresholds.warnLines} lines.`);
  out.push('');
  if (r.violations.length) {
    out.push(`Import boundary violations (${r.violations.length}):`);
    for (const v of r.violations) out.push(`  FAIL  [${v.rule}] ${v.at}  "${v.specifier}"  ${v.message}`);
  } else out.push('Import boundaries: ok.');
  out.push('');
  if (r.cycles.length) {
    out.push(`Workspace dependency cycles (${r.cycles.length}):`);
    for (const c of r.cycles) out.push(`  FAIL  ${c.path.join(' → ')}${c.members.length > c.path.length - 1 ? `  (component: ${c.members.join(', ')})` : ''}`);
  } else out.push('Workspace dependency graph: acyclic.');
  out.push('');
  out.push(r.ok ? `PASS with ${r.warnings} warning(s).` : `FAILED: ${r.failures} failure(s), ${r.warnings} warning(s).`);
  console.log(out.join('\n'));
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const args = parseArgs(process.argv.slice(2));
  if (!existsSync(args.root)) usage(`root ${args.root} does not exist`);
  const report = runGuards(args.root);
  if (args.json) console.log(JSON.stringify(report, null, 2));
  else printReport(report);
  process.exitCode = report.ok ? 0 : 1;
}
